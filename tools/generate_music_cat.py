#!/usr/bin/env python3
"""Rasterize the original integer-grid SVGs into transparent LVGL ARGB8888 Flash sprites."""
from pathlib import Path
import xml.etree.ElementTree as ET
from PIL import Image, ImageDraw
ROOT=Path(__file__).resolve().parents[1]
out=['// Original Passport Music pixel cat. Generated by tools/generate_music_cat.py.','#include "lvgl.h"']
for kind,state in ((kind,state) for kind in ('cat','dog','rabbit','penguin') for state in ('play','rest')):
    source=ROOT/f'assets/images/music-{kind}-{state}.svg'
    image=Image.new('RGBA',(32,32),(0,0,0,0)); draw=ImageDraw.Draw(image)
    for element in ET.parse(source).getroot():
        if element.tag.endswith('rect'):
            x,y,w,h=(int(element.attrib[k]) for k in ('x','y','width','height'))
            draw.rectangle((x,y,x+w-1,y+h-1),fill=element.attrib['fill'])
        elif element.tag.endswith('polygon'):
            pts=[tuple(map(int,v.split(','))) for v in element.attrib['points'].split()]
            draw.polygon(pts,fill=element.attrib['fill'])
        else: raise ValueError(element.tag)
    image=image.resize((40,40),Image.Resampling.NEAREST)
    data=bytearray()
    for r,g,b,a in image.get_flattened_data():
        data.extend((b,g,r,a))
    out.append(f'static const uint8_t {kind}_{state}_data[] = {{')
    out.extend(','.join(f'0x{x:02x}' for x in data[i:i+32])+',' for i in range(0,len(data),32))
    out.append('};')
    out.append(f'''const lv_image_dsc_t music_{kind}_{state} = {{
    .header={{.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_ARGB8888,.w=40,.h=40,.stride=160}},
    .data_size=sizeof({kind}_{state}_data),.data={kind}_{state}_data
}};''')
(ROOT/'assets/images/music_cat.c').write_text('\n'.join(out)+'\n',encoding='utf-8')
print('Original pets: eight40x40 ARGB8888 sprites,51200 Flash bytes, shared pose/position')
