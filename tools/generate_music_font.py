#!/usr/bin/env python3
"""Emit verified LVGL PLAIN 2bpp glyphs using Pillow, without Node converters."""
import argparse
import hashlib
import json
from pathlib import Path
import unicodedata
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "assets/fonts/NotoSansSC-Regular.ttf"
OUTPUT = FONT.with_name("music_font_16.c")
INVENTORY = FONT.with_name("music_font_inventory.json")
RANGES = [(0x20,0x7e),(0xa0,0x24f),(0x2000,0x206f),(0x20a0,0x22ff),
          (0x2460,0x24ff),(0x25a0,0x26ff),(0x3000,0x303f),
          (0x4e00,0x9fff),(0xff00,0xffef)]
EXTRA = {0x30fb}
# Same centered-dot shape for two absent mathematical dot glyphs. Preserve
# original Unicode in input/output; only their bitmap source is aliased.
ALIASES = {0x2219:0xb7,0x22c5:0xb7}

def generate():
    cmap = TTFont(FONT).getBestCmap()
    requested = sorted({cp for lo,hi in RANGES for cp in range(lo,hi+1)}|EXTRA)
    chars = [cp for cp in requested if ALIASES.get(cp,cp) in cmap
             and unicodedata.category(chr(cp)) not in ('Cc','Cf','Cn','Zl','Zp')]
    missing = sorted(set(requested) - set(chars))
    font = ImageFont.truetype(str(FONT), 16)
    font.set_variation_by_axes([400])
    bitmap = bytearray()
    descriptors = [(0, 0, 0, 0, 0, 0)]
    for cp in chars:
        ch = chr(ALIASES.get(cp,cp))
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = x1-x0, y1-y0
        img = Image.new("L", (max(1, w), max(1, h)))
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        pixels = [round(v * 3 / 255) for v in img.get_flattened_data()] if w*h else []
        start = len(bitmap)
        packed = bytearray()
        for offset in range(0, len(pixels), 4):
            four = pixels[offset:offset+4] + [0]*max(0, offset+4-len(pixels))
            packed.append(sum(v << (6-i*2) for i, v in enumerate(four)))
        # Read exactly like LVGL's plain 2bpp decoder and compare every pixel.
        decoded = [(packed[i//4] >> (6-(i%4)*2)) & 3 for i in range(len(pixels))]
        assert decoded == pixels, hex(cp)
        bitmap.extend(packed)
        descriptors.append((start, round(font.getlength(ch)*16), w, h, x0, -y1))
    out = ['// Generated by tools/generate_music_font.py; Noto Sans SC, SIL OFL 1.1.', '#include "lvgl.h"',
           'static const uint8_t bitmap[] = {']
    for i in range(0, len(bitmap), 32):
        out.append(','.join(f'0x{x:02x}' for x in bitmap[i:i+32])+',')
    out.append('};\nstatic const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {')
    for idx, adv, w, h, x, y in descriptors:
        out.append(f'{{.bitmap_index={idx},.adv_w={adv},.box_w={w},.box_h={h},.ofs_x={x},.ofs_y={y}}},')
    out.append('};\nstatic const uint16_t unicode_list[] = {')
    out.extend(','.join(str(cp-0x20) for cp in chars[i:i+32])+',' for i in range(0, len(chars), 32))
    out.append('''};
static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    .range_start=0x20, .range_length=0xffd0, .glyph_id_start=1,
    .unicode_list=unicode_list, .glyph_id_ofs_list=NULL,
    .list_length=sizeof(unicode_list)/sizeof(unicode_list[0]),
    .type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY
}};
static lv_font_fmt_txt_dsc_t dsc = {
    .glyph_bitmap=bitmap, .glyph_dsc=glyphs, .cmaps=cmaps, .cmap_num=1,
    .bpp=2, .kern_scale=0, .kern_dsc=NULL, .kern_classes=0, .bitmap_format=0
};
const lv_font_t music_font_16 = {
    .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,
    .line_height=22, .base_line=4, .subpx=LV_FONT_SUBPX_NONE,
    .underline_position=-2, .underline_thickness=1, .dsc=&dsc
};''')
    OUTPUT.write_text('\n'.join(out)+'\n', encoding='utf-8')
    inventory = dict(font_sha256=hashlib.sha256(FONT.read_bytes()).hexdigest(),
                     generated_sha256=hashlib.sha256(OUTPUT.read_bytes()).hexdigest(),
                     codepoints=chars, missing=missing, bitmap_bytes=len(bitmap), size=16, bpp=2,
                     ranges=RANGES,extra=sorted(EXTRA),glyph_aliases={str(k):v for k,v in ALIASES.items()},
                     unicode_version=unicodedata.unidata_version)
    INVENTORY.write_text(json.dumps(inventory, indent=2)+'\n', encoding='utf-8')
    FONT.with_name('music_font_coverage.h').write_text(
        '// Generated coverage; absent characters are rendered as a visible question mark.\n'
        '#pragma once\n#include <stdbool.h>\n#include <stdint.h>\n'
        'static inline bool music_font_supported(uint32_t cp) {\n'
        'static const uint16_t missing[] = {' + ','.join(str(c) for c in missing) + '};\n'
        'bool range = '+' || '.join(f'(cp>=0x{lo:x} && cp<=0x{hi:x})' for lo,hi in RANGES)+
        ''.join(f' || cp==0x{cp:x}' for cp in sorted(EXTRA))+';\n'
        'if (!range) return false;\n'
        'unsigned lo=0,hi=sizeof(missing)/sizeof(missing[0]);\n'
        'while (lo<hi) { unsigned mid=lo+(hi-lo)/2; if (missing[mid]<cp) lo=mid+1; else hi=mid; }\n'
        'return lo==sizeof(missing)/sizeof(missing[0]) || missing[lo]!=cp;\n}\n', encoding='utf-8')
    print(f'Font: {len(chars)} glyphs, {len(bitmap)} bitmap bytes; {len(missing)} unavailable requested codepoints')

def check():
    inv = json.loads(INVENTORY.read_text())
    assert hashlib.sha256(OUTPUT.read_bytes()).hexdigest() == inv['generated_sha256']
    supported = set(inv['codepoints'])
    # Only actual string literals, excluding source comments/identifiers.
    import re
    for file in (ROOT/'main').glob('music_ui.c'):
        for literal in re.findall(r'"([^"\n]*)"', file.read_text(encoding='utf-8')):
            for ch in literal:
                if ord(ch) > 127: assert ord(ch) in supported, (file, ch)
    assert set(range(0x4e00, 0x9ff0)) <= supported
    print(f'Chinese UI coverage and U+4E00-U+9FEF: PASS ({len(supported)} glyphs)')

if __name__ == '__main__':
    ap = argparse.ArgumentParser(); ap.add_argument('--check', action='store_true')
    if ap.parse_args().check: check()
    else: generate(); check()
